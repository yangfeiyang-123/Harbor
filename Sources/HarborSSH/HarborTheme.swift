import AppKit
import SwiftUI

/// Shared with the offline CodeMirror/Markdown bundle; see Themes/SOURCES.md.
enum HarborTheme {
    /// One stored value combines palette family and mode, so every surface
    /// that already observes "appearance" follows both without extra wiring.
    /// `anthropic` follows macOS; the suffixed values pin light or dark. The other families
    /// are stored the same way ("tide", "tide-light", "tide-dark"); the standard colors have
    /// no name of their own, and their value is the bare mode.
    static let anthropic = "anthropic"
    /// A palette family: a light and a dark palette under one name.
    struct Family: Identifiable, Hashable {
        /// What stands before the mode in the stored value; empty for the standard colors.
        let id: String
        let title: String
        /// What its Code-OSS color themes are called, before " Light" and " Dark".
        let editor: String
        /// Its palettes in Themes. The standard colors have none of their own: native pages
        /// read vscode-2026.json, the editor and the pages around it cursor.json.
        let file: String?
        /// One line for Settings.
        let note: String
    }
    static let standard = Family(id: "", title: "Standard", editor: "Harbor", file: nil,
                                 note: "Standard is neutral gray with a blue accent, and the only one Liquid Glass applies to.")
    static let claude = Family(id: anthropic, title: "Claude", editor: "Harbor Anthropic", file: "anthropic.json",
                               note: "Claude pairs ivory paper or warm charcoal with one clay accent.")
    /// Harbor's own families, generated by scripts/build-themes.py from the same tokens as Claude.
    static let designed: [Family] = [
        Family(id: "tide", title: "Tide", editor: "Harbor Tide", file: "tide.json",
               note: "Tide is fog-blue paper or deep-sea navy with one sea-blue accent."),
        Family(id: "kelp", title: "Kelp", editor: "Harbor Kelp", file: "kelp.json",
               note: "Kelp is lichen paper or pine black with moss green."),
        Family(id: "dusk", title: "Dusk", editor: "Harbor Dusk", file: "dusk.json",
               note: "Dusk is lilac paper or aubergine with violet."),
        Family(id: "fog", title: "Fog", editor: "Harbor Fog", file: "fog.json",
               note: "Fog is grays only: the accent is ink, and syntax is spoken quietly."),
        Family(id: "lighthouse", title: "Lighthouse", editor: "Harbor Lighthouse", file: "lighthouse.json",
               note: "Lighthouse is white or pitch black at full contrast, with one amber beam.")]
    /// In the order Settings shows them.
    static let families: [Family] = [claude, standard] + designed
    static let appearances: [String] = ["system", "light", "dark"] + families.filter { !$0.id.isEmpty }.flatMap { [$0.id, $0.id + "-light", $0.id + "-dark"] }
    /// The Claude theme, following macOS for light and dark.
    static let defaultAppearance = anthropic
    static var selection: String { UserDefaults.standard.string(forKey: "appearance") ?? defaultAppearance }
    /// Harbor's own look is the Claude theme. Run once at launch: the standard themes stay
    /// available in Settings, but an install that was on them moves over, keeping its light,
    /// dark or automatic choice.
    static func adoptDefaultAppearance(_ defaults: UserDefaults = .standard) {
        defaults.register(defaults: ["appearance": defaultAppearance])
        guard defaults.integer(forKey: "appearanceDefaultRevision") < 1 else { return }
        defaults.set(1, forKey: "appearanceDefaultRevision")
        if let stored = defaults.string(forKey: "appearance"), isStandard(stored) {
            defaults.set(compose(anthropic: true, mode: mode(stored)), forKey: "appearance")
        }
    }
    /// The family's part of a stored value: what stands before "-light" or "-dark", and nothing
    /// for the standard colors. Cheap: colors ask on every draw.
    static func familyID(_ selection: String) -> String {
        if selection == "system" || selection == "light" || selection == "dark" { return "" }
        if selection.hasSuffix("-light") { return String(selection.dropLast(6)) }
        if selection.hasSuffix("-dark") { return String(selection.dropLast(5)) }
        return selection
    }
    /// A value that names no family Harbor has is the standard colors.
    static func family(_ selection: String) -> Family {
        let id = familyID(selection)
        return families.first(where: { $0.id == id }) ?? standard
    }
    static func isAnthropic(_ selection: String) -> Bool { familyID(selection) == anthropic }
    /// The standard colors: the ones without a palette file of their own.
    static func isStandard(_ selection: String) -> Bool { family(selection).file == nil }
    static func mode(_ selection: String) -> String {
        selection.hasSuffix("dark") ? "dark" : selection.hasSuffix("light") ? "light" : "system"
    }
    /// Resolved darkness for surfaces that are created outside SwiftUI's color scheme.
    @MainActor static func isDark(_ selection: String = selection) -> Bool {
        switch mode(selection) {
        case "dark": return true
        case "light": return false
        default: return NSApp.effectiveAppearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
        }
    }
    /// The Code-OSS color theme contributed by Harbor's bundled theme extension.
    static func editorThemeName(dark: Bool, selection: String = selection) -> String {
        family(selection).editor + (dark ? " Dark" : " Light")
    }
    static let editorThemeNames: [String] = families.flatMap { [$0.editor + " Light", $0.editor + " Dark"] }
    /// The editor's background in one of Harbor's Code-OSS themes ("Harbor Tide Dark"), as the
    /// page writes it (lowercase #rrggbb): a page with that background wears that theme. The
    /// themes are made from these same palettes (CodeWorkbench's bundled theme extension); the
    /// standard pair from cursor.json. Nil for a name Harbor does not make, or a background that
    /// is not opaque (the page writes those as rgba()).
    static func editorBackground(_ editorTheme: String) -> String? {
        let dark = editorTheme.hasSuffix(" Dark")
        guard dark || editorTheme.hasSuffix(" Light") else { return nil }
        let name = String(editorTheme.dropLast(dark ? 5 : 6))
        guard let family = families.first(where: { $0.editor == name }) else { return nil }
        let pair = family.file == nil ? cursorPalettes : lightAndDark(of: family)
        guard let value = pair[dark ? "dark" : "light"]?.colors["editor.background"]?.lowercased(), value.hasPrefix("#") else { return nil }
        if value.count == 9 { return value.hasSuffix("ff") ? String(value.prefix(7)) : nil }
        return value.count == 7 ? value : nil
    }
    /// The palettes the standard editor themes are made from.
    static let cursorPalettes: [String: Palette] = {
        let url = AppResources.directory("Themes").appendingPathComponent("cursor.json")
        return (try? JSONDecoder().decode([String: Palette].self, from: Data(contentsOf: url))) ?? [:]
    }()
    static func compose(family: Family, mode: String) -> String {
        family.id.isEmpty ? mode : (mode == "system" ? family.id : family.id + "-" + mode)
    }
    static func compose(anthropic claudeFamily: Bool, mode: String) -> String {
        compose(family: claudeFamily ? claude : standard, mode: mode)
    }
    struct Palette: Decodable {
        let name: String
        let colors: [String: String]
        let syntax: [String: String]
        let ansi: [String]
    }
    static let palettes: [String: Palette] = {
        let url = AppResources.directory("Themes").appendingPathComponent("vscode-2026.json")
        return try! JSONDecoder().decode([String: Palette].self, from: Data(contentsOf: url))
    }()
    /// The palettes of the families that have a file, by family id.
    private static let loadedPalettes: [String: [String: Palette]] = {
        var loaded: [String: [String: Palette]] = [:]
        for family in families {
            guard let file = family.file else { continue }
            let url = AppResources.directory("Themes").appendingPathComponent(file)
            loaded[family.id] = try! JSONDecoder().decode([String: Palette].self, from: Data(contentsOf: url))
        }
        return loaded
    }()
    static let anthropicPalettes: [String: Palette] = loadedPalettes[anthropic]!
    /// A family's light and dark palettes; the standard colors' native ones for a family without a file.
    static func lightAndDark(of family: Family) -> [String: Palette] { loadedPalettes[family.id] ?? palettes }
    static func scheme(_ selection: String) -> ColorScheme? {
        switch mode(selection) { case "dark": return .dark; case "light": return .light; default: return nil }
    }
    static func palette(dark: Bool, selection: String = selection) -> Palette {
        (loadedPalettes[familyID(selection)] ?? palettes)[dark ? "dark" : "light"]!
    }
    static func native(_ role: String, dark: Bool, selection: String = selection) -> NSColor {
        hex(palette(dark: dark, selection: selection).colors[role]!)
    }
    static func hex(_ value: String) -> NSColor {
        let digits = String(value.dropFirst())
        let raw = UInt32(digits, radix: 16)!
        let rgb = digits.count == 8 ? raw >> 8 : raw
        let alpha = digits.count == 8 ? Double(raw & 255) / 255 : 1
        return NSColor(srgbRed: Double((rgb >> 16) & 255) / 255, green: Double((rgb >> 8) & 255) / 255,
                       blue: Double(rgb & 255) / 255, alpha: alpha)
    }
    /// One color object per theme and role. A new one on every use made each view look changed
    /// to SwiftUI whenever anything above it was updated.
    private static var adaptiveColors: [String: NSColor] = [:]
    private static let adaptiveLock = NSLock()
    static func adaptive(_ role: String) -> NSColor {
        let selected = selection, name = "Harbor." + selected + "." + role
        adaptiveLock.lock(); defer { adaptiveLock.unlock() }
        if let color = adaptiveColors[name] { return color }
        let color = NSColor(name: NSColor.Name(name)) { appearance in
            native(role, dark: appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua, selection: selected)
        }
        adaptiveColors[name] = color
        return color
    }
}

